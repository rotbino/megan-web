/**
 * مسیر صفحه جستجوی سئو-پسند هر عبارت — /product-list/search/{عبارت کدشده}.
 * هر جستجو URL اختصاصی و ایندکس‌پذیر خودش را می‌گیرد (به‌جای ?s= کوئری‌استرینگ).
 */
export function searchPath(q: string): string {
  return `/product-list/search/${encodeURIComponent(q.trim())}`;
}
