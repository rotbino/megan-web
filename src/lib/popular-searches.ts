/** نرمال‌سازی پایه — عربی→فارسی، ارقام فارسی→لاتین، نیم‌فاصله→فاصله، اعراب‌زدایی */
function normalizeText(raw: string): string {
  return raw
    .replace(/ي/g, 'ی')
    .replace(/ك/g, 'ک')
    .replace(/[۰-۹]/g, (d) => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d)))
    .replace(/\u200c/g, ' ')
    .replace(/[\u064b-\u0652\u0670]/g, '')
    .replace(/[؟?!.،,؛:«»"'()\[\]{}+\-_/\\]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * حذف کلمات اضافه از عبارت جستجو — خروجی «عبارت هسته‌ای» است:
 *   'خرید سیب زمینی عمده در تهران' → 'سیب زمینی'
 *   'زرشک عمده'                    → 'زرشک'
 *   'قیمت پسته'                     → 'پسته'
 * ارقام و واحدها هم می‌ریزند تا تطبیق با نام آگهی ممکن شود.
 * اگر همهٔ عبارت حذف شود، خودِ عبارتِ نرمال‌شده برگردد (جستجو خالی نشود).
 * تابع خودتوان (idempotent) است — روی عبارت پاک‌شده تغییری نمی‌دهد.
 */
export function stripSearchNoise(raw: string): string {
  const norm = normalizeText(raw);
  if (!norm) return '';

  const kept = norm
    .split(' ')
    .map((t) => t.replace(/[0-9]+/g, '')) // ارقام داخل توکن: «۵۰۰گرمی» → «گرمی»
    .filter((t) => t.length > 0)
    .filter((t) => !TRADE_NOISE.has(t) && !LOCATION_WORDS.has(t));

  return kept.join(' ') || norm;
}

/**
 * مسیر صفحه جستجوی سئو-پسند — /product-list/search/{عبارت هسته‌ای کدشده}.
 * هر ورودی گوگل (چه از فوتر، چه تایپ کاربر) اول پاکسازی می‌شود تا صفحه
 * مقصد همیشه کنونیکالِ یکتا و نتیجه‌دار باشد.
 */
export function searchPath(q: string): string {
  return `/product-list/search/${encodeURIComponent(stripSearchNoise(q))}`;
}
