/**
 * ─── متن پیش‌فرض «توضیحات کسب‌وکار» — پارامتریک و فقط در لحظهٔ نمایش ────────
 *
 * خواستهٔ مالک (۱۳-۱۱): کاربری که (از باسکول آمده و) چیزی برای کسب‌وکارش
 * ننوشته، این متن را می‌بیند — نه متن خودکار باسکول را («… در حال خرید و
 * فروش عمده در بازار بزرگ باسکول…»). متن عمداً متفاوت با باسکول نوشته
 * شده و هرگز در دیتابیس/پروفایل کاربر ذخیره نمی‌شود؛ صفحات مربوطه
 * (کاتالوگ عمومی، دفتر خرید عمومی) آن را از همین متادیتای مشترک فرانت
 * می‌خوانند و با نام و شهرِ همان کاربر می‌سازند.
 */

export interface FallbackBusinessDescInput {
  /** نام کامل فروشنده/خریدار — نبود: «این فروشنده»/«این خریدار» */
  name?: string | null;
  /** شهر (اگر نبود، استان) — جملهٔ «از شهر …» فقط با وجودش ساخته می‌شود */
  city?: string | null;
  /** خریدار = متن دفتر خرید عمومی؛ پیش‌فرض فروشنده */
  kind?: 'seller' | 'buyer';
  /** نمونهٔ کوتاه برای جاهای کم‌جا (سایدبار) — بدون جملهٔ پایانی */
  short?: boolean;
}

/** متن پیش‌فرض «توضیحات کسب‌وکار» — نمایشی، پارامتریک، غیرذخیره */
export function fallbackBusinessDesc(input: FallbackBusinessDescInput = {}): string {
  const kind = input.kind ?? 'seller';
  const name = (input.name ?? '').trim() || (kind === 'buyer' ? 'این خریدار' : 'این فروشنده');
  const city = (input.city ?? '').trim();
  const from = city ? ` از شهر ${city}` : '';

  if (kind === 'buyer') {
    return [
      `${name} هستم${from} و در بازار آنلاین آیمچ به‌صورت عمده خرید می‌کنم.`,
      'کالاهای دوره‌ای و نیازهای خریدم را در این دفتر خرید منتشر می‌کنم؛',
      'برای ارتباط و ارائهٔ پیشنهاد کالا، از طریق همین صفحه با من در تماس باشید.',
    ].join(' ');
  }

  const base = [
    `${name} هستم${from} و در بازار آنلاین آیمچ به‌صورت عمده خرید و فروش می‌کنم.`,
    'قیمت و موجودی کالاها را در همین کاتالوگ به‌روز نگه می‌دارم؛',
    'برای استعلام و سفارش، از دکمهٔ «ارسال پیام» استفاده کنید.',
  ].join(' ');

  return input.short ? base : `${base} اگر این کاتالوگ برایتان مفید بود، آن را با همکارانتان به اشتراک بگذارید.`;
}
